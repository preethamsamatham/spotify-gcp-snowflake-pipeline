CREATE OR REPLACE VIEW SPOTIFY_DB.ANALYTICS.VW_ARTIST_SUMMARY
COMMENT = 'One row per artist with catalog-level song metrics'
AS
SELECT
    AR.ARTIST_ID,
    AR.NAME AS ARTIST_NAME,

    COUNT(DISTINCT S.SONG_ID) AS SONG_COUNT,
    COUNT(DISTINCT S.ALBUM_ID) AS ALBUM_COUNT,

    ROUND(AVG(S.DURATION_MS) / 1000.0, 1)
        AS AVG_SONG_DURATION_SECONDS,

    COUNT_IF(S.EXPLICIT = TRUE)
        AS EXPLICIT_SONG_COUNT,

    ROUND(
        100.0 * COUNT_IF(S.EXPLICIT = TRUE)
        / NULLIF(COUNT(DISTINCT S.SONG_ID), 0),
        1
    ) AS EXPLICIT_SONG_PERCENTAGE,

    MIN(S.ADDED_AT) AS FIRST_SONG_ADDED_AT,
    MAX(S.ADDED_AT) AS LATEST_SONG_ADDED_AT

FROM SPOTIFY_DB.RAW.ARTISTS AS AR

JOIN SPOTIFY_DB.RAW.SONG_ARTISTS AS SA
    ON AR.ARTIST_ID = SA.ARTIST_ID

JOIN SPOTIFY_DB.RAW.SONGS AS S
    ON SA.SONG_ID = S.SONG_ID

GROUP BY
    AR.ARTIST_ID,
    AR.NAME;
    --------------------------------------------
    SELECT
    COUNT(*) AS VIEW_ROWS,
    COUNT(DISTINCT ARTIST_ID) AS UNIQUE_ARTISTS,
    SUM(SONG_COUNT) AS TOTAL_ARTIST_SONG_RELATIONSHIPS,
    COUNT_IF(SONG_COUNT = 0) AS ARTISTS_WITHOUT_SONGS
FROM SPOTIFY_DB.ANALYTICS.VW_ARTIST_SUMMARY;
----------------------------
SELECT
    ARTIST_NAME,
    SONG_COUNT,
    ALBUM_COUNT
FROM SPOTIFY_DB.ANALYTICS.VW_ARTIST_SUMMARY
ORDER BY SONG_COUNT DESC, ARTIST_NAME
LIMIT 10;
------------------------------
SELECT
    COUNT(*) AS VIEW_ROWS,
    COUNT(DISTINCT ARTIST_ID) AS UNIQUE_ARTISTS,
    SUM(SONG_COUNT) AS TOTAL_ARTIST_SONG_RELATIONSHIPS,
    COUNT_IF(SONG_COUNT = 0) AS ARTISTS_WITHOUT_SONGS
FROM SPOTIFY_DB.ANALYTICS.VW_ARTIST_SUMMARY;

SELECT COUNT(*)
FROM SPOTIFY_DB.ANALYTICS.VW_SONG_CATALOG;
