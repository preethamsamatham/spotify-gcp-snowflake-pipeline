CREATE OR REPLACE VIEW VW_SONG_CATALOG
COMMENT = 'One row per unique song observed by the pipeline; not current playlist membership'
AS
SELECT
    S.SONG_ID,
    S.NAME AS SONG_NAME,
    S.DURATION_MS,
    ROUND(S.DURATION_MS / 1000.0, 1) AS DURATION_SECONDS,
    S.EXPLICIT,
    S.TRACK_NUMBER,
    S.ADDED_AT,
    TO_DATE(S.ADDED_AT) AS ADDED_DATE,

    A.ALBUM_ID,
    A.NAME AS ALBUM_NAME,
    A.RELEASE_DATE AS RELEASE_DATE_RAW,
    TRY_TO_NUMBER(LEFT(A.RELEASE_DATE, 4)) AS RELEASE_YEAR,
    A.TOTAL_TRACKS AS ALBUM_TOTAL_TRACKS,

    LISTAGG(DISTINCT AR.NAME, ', ')
        WITHIN GROUP (ORDER BY AR.NAME) AS ARTIST_NAMES,

    COUNT(DISTINCT AR.ARTIST_ID) AS ARTIST_COUNT

FROM SPOTIFY_DB.RAW.SONGS AS S

LEFT JOIN SPOTIFY_DB.RAW.ALBUMS AS A
    ON S.ALBUM_ID = A.ALBUM_ID

LEFT JOIN SPOTIFY_DB.RAW.SONG_ARTISTS AS SA
    ON S.SONG_ID = SA.SONG_ID

LEFT JOIN SPOTIFY_DB.RAW.ARTISTS AS AR
    ON SA.ARTIST_ID = AR.ARTIST_ID

GROUP BY
    S.SONG_ID,
    S.NAME,
    S.DURATION_MS,
    S.EXPLICIT,
    S.TRACK_NUMBER,
    S.ADDED_AT,
    A.ALBUM_ID,
    A.NAME,
    A.RELEASE_DATE,
    A.TOTAL_TRACKS;

    ----------------------------
    SELECT
    COUNT(*) AS VIEW_ROWS,
    COUNT(DISTINCT SONG_ID) AS UNIQUE_SONGS,
    COUNT_IF(ARTIST_COUNT = 0) AS SONGS_WITHOUT_ARTISTS,
    COUNT_IF(ALBUM_ID IS NULL) AS SONGS_WITHOUT_ALBUMS
FROM SPOTIFY_DB.ANALYTICS.VW_SONG_CATALOG;
